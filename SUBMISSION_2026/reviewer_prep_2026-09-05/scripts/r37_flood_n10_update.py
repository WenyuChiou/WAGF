# Part 2
# =============================================================================
def _contrast(rows: list, per_run: dict, seeds: list, row_type: str) -> None:
    n = len(seeds)
    for label in METRIC_LABELS:
        diffs = []
        seeds_used = []
        for seed in seeds:
            s = per_run.get(("strict", seed))
            d = per_run.get(("disabled", seed))
            if s is None or d is None:
                continue
            diffs.append(float(s[label]) - float(d[label]))
            seeds_used.append(seed)
            rows.append({"row_type": "diff_pair", "section": row_type, "metric": label,
                         "seed": seed, "strict_value": float(s[label]),
                         "disabled_value": float(d[label]),
                         "diff_strict_minus_disabled": diffs[-1]})
        if len(seeds_used) < 2:
            print(f"  {row_type} PENDING: {label} -- only {len(seeds_used)}/{n} seeds ready "
                  f"(need >=2 for paired t)")
            rows.append({"row_type": "skipped", "section": row_type, "metric": label,
                         "reason": f"only {len(seeds_used)}/{n} seeds ready"})
            continue
        stats = R28._sign_stats(diffs)
        complete = len(seeds_used) == n
        rows.append({"row_type": row_type, "metric": label, "n_pairs": stats["n_pairs"],
                     "n_seeds_expected": n, "complete": complete,
                     "seeds_used": ",".join(seeds_used), "mean_diff": stats["mean_diff"],
                     "sd_diff": stats["sd_diff"], "min_diff": stats["min_diff"],
                     "max_diff": stats["max_diff"], "t": stats["t"], "df": stats["df"],
                     "p_paired_t": stats["p_paired_t"],
                     "p_exact_permutation": stats["p_exact_permutation"],
                     "permutation_floor": stats["permutation_floor"],
                     "n_sign_flips": stats["n_sign_flips"], "all_same_sign": stats["all_same_sign"]})
        print(f"  {row_type}: {label} -- n={stats['n_pairs']}{'' if complete else ' (PARTIAL)'} "
              f"mean_diff={stats['mean_diff']:.3f} t={stats['t']:.3f} df={stats['df']:.0f} "
              f"p_perm={stats['p_exact_permutation']:.5f} (floor {stats['permutation_floor']:.5f}) "
              f"all_same_sign={stats['all_same_sign']}")


