def _part1(rows: list, corpus: str = "v08") -> dict:
    """Returns {(arm, seed): {metric_label: value, ...}} for complete runs."""
    per_run: dict = {}
    for arm in ARMS:
        for seed in N10_SEEDS:
            run_dir = _run_dir(arm, seed, corpus)
            status, reason = R34._flood_run_completeness(run_dir)
            vintage = corpus if corpus != "v08" else ("ext" if seed in EXT_SEEDS else "faf1bb12")
            if status == "skipped":
                print(f"  SKIPPED {arm} seed {seed}: {reason}")
                rows.append({"row_type": "skipped", "arm": arm, "seed": seed,
                             "vintage": vintage, "reason": reason})
                continue
            m = R23._metrics_for(run_dir)
            metric_values = {label: m[R34._rep_metric(label)] for label in METRIC_LABELS}
            row = {"row_type": "run_metrics", "arm": arm, "seed": seed,
                   "vintage": vintage, "n_rows": m["_n_rows"]}
            row.update({f"metric__{i}": metric_values[label] for i, label in enumerate(METRIC_LABELS)})
            rows.append(row)
            print(f"  OK {arm:9s} seed {seed} ({row['vintage']}): rows={m['_n_rows']} "
                  f"ibr_uncond_final={m['ibr_uncond_final']:.2f}% "
                  f"ehe_pooled={m['ehe_pooled_simlog_published']:.4f}")

            manifest = R34._manifest_fields(run_dir)
            model = manifest.get("model")
            git_commit = manifest.get("git_commit")
            # v08: value-enforced ONLY for the 5 ext seeds (faf1bb12 seeds were
            # already enforced when r23/r24 first ingested them). defaults: the
            # WHOLE 10-seed corpus is new (nothing pre-enforced), so every seed
            # is enforced, against commit 83fa97e1 (same expected prefix as ext).
            enforced = (seed in EXT_SEEDS) if corpus == "v08" else True
            if enforced:
                if model != "gemma3:4b":
                    raise PrepError(f"{run_dir}: model={model!r}, expected 'gemma3:4b'")
                if not str(git_commit or "").startswith("83fa97e1"):
                    raise PrepError(f"{run_dir}: git_commit={git_commit!r}, expected to "
                                     f"start with '83fa97e1'")
            rows.append({"row_type": "manifest_check", "arm": arm, "seed": seed,
                         "vintage": row["vintage"], "model": model,
                         "git_commit_short": (git_commit or "")[:8], "enforced": enforced})

            per_run[(arm, seed)] = metric_values
    return per_run


