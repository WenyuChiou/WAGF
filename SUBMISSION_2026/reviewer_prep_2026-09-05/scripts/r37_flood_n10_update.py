"""R37 -- flood governed-vs-ungoverned at n=10: extends the existing 5-seed
(42-46, faf1bb12) contrast with 5 new seeds (47-51, `_ext` suffix, commit
83fa97e1), and reports the n=5 and n=10 contrasts side by side. CPU-only
(GPU busy -- no LLM calls, existing/landing CSVs only).

BACKGROUND -- the corpus is a MIXED CODE VINTAGE, stated up front, never
glossed over
  Seeds 42-46: `JOH_{strict,disabled}_gemma3_4b_faf1bb12/Run_{42..46}`,
  ALREADY COMPLETE, commit faf1bb12. Seeds 47-51: `JOH_{strict,disabled}_
  gemma3_4b_83fa97e1_ext/Run_{47..51}`, PARTIAL when the 0.8 queue was
  stopped on 2026-09-23 (strict 47-49 landed, disabled none); the 0.8 n=10
  set was abandoned in favour of --corpus defaults, commit 83fa97e1. The task brief that commissioned
  this script describes a "mock byte-identity chain faf1bb12 -> c3391a53 ->
  83fa97e1" documented in a "regen_progress" file, as the basis for treating
  the two commits' flood code paths as equivalent for this contrast. This
  script LOOKED for that documentation and could not find it in this
  worktree: `.ai/regen_progress_section_2026-09-21.md`,
  `_section_r33.md`, `_section_r34.md` were checked directly (grepped for
  "byte-identity", "mock", "83fa97e1", "c3391a53" -- no hits in any of the
  three) and no other `regen_progress*` file exists under `.ai/`. This
  script does NOT claim to have independently verified byte-identity
  across the three commits' flood code paths -- it reports the corpus
  exactly as the task brief describes it (mixed vintage, mock-verified per
  the brief, not per this script's own check), states that the supporting
  document could not be located here, and never pools the two vintages
  silently as if they were a single homogeneous run of 10 seeds without
  flagging the mix at every table that combines them.

PART 1 -- per (arm, seed): r23's six collapsed metrics
  `_metrics_for()` imported from r23_flood_strict_regen.py (not re-derived,
  the exact function r34 also reuses): 3 IBR conditionings (final level) +
  EHE pooled simlog + rejection rate + retry rate. Manifest census
  (model=="gemma3:4b", git_commit prefix) is read and reported for every
  seed; VALUE-ENFORCED (raises otherwise) only for the 5 new seeds
  (47-51, expected git_commit prefix "83fa97e1") -- the faf1bb12 seeds are
  read/reported only, never enforced (they were already enforced when
  r23/r24 first ingested them).

PART 2 -- governed-vs-ungoverned contrast, n=10 and n=5 side by side
  For each of the 6 metrics: per-seed (strict - disabled) difference,
  `R28._sign_stats()` (imported from r28_trajectory_vs_traditional.py, not
  re-derived -- computes paired t [df = n-1], `C.exact_perm_p` [see the
  FLOOR NOTE below], sign-flip count, all-same-sign flag, mean/sd/min/max
  diff, all in one call) over the full n=10 corpus AND, separately, over
  the original n=5 (faf1bb12-only) subset, so the two are directly
  comparable in one table rather than requiring a second script's CSV.

FLOOR NOTE -- the task brief's stated permutation floor is wrong; corrected
  here, not silently used
  The task brief states "exact permutation (2^10, floor 0.00098)" for n=10.
  `_common.py::exact_perm_p`'s own docstring states the floor is
  `2/2^n` (two sign-assignments -- the observed one and its total
  complement -- always tie the observed |mean| exactly), which for n=10 is
  `2/1024 = 0.001953125`, almost exactly DOUBLE the brief's stated
  0.00098 (which equals `1/1024`, one assignment, not two). This script
  computes the floor directly as `2.0 / (1 << n)` (also what
  `R28._sign_stats` itself returns as `permutation_floor`) for both n=10
  and n=5 rather than hand-typing either number, and the discrepancy is
  reported back to the task's requester rather than silently adopting the
  brief's figure.

COMPLETENESS GATE
  Per (arm, seed): `R34._flood_run_completeness` (imported from
  r34_placebo_retry_flood.py, not re-derived -- dir exists ->
  household_governance_audit.csv -> simulation_log.csv ->
  run_integrity.json(integrity_ok==True)). Missing any -> row_type=skipped,
  printed pending reason, that seed excluded from both the n=10 and (if it
  is one of the 5 new seeds) implicitly from the n=5 subset it was never
  part of anyway.

OUTPUTS
  out/r37_flood_n10_update.csv -- row_type in {skipped, run_metrics,
    manifest_check, diff_pair, contrast_n10, contrast_n5}.
  out/r37_flood_n10_update.md -- GENERATED by render_md() directly from
    that same `rows` list.

Usage:  python SUBMISSION_2026/reviewer_prep_2026-09-05/scripts/r37_flood_n10_update.py
        python SUBMISSION_2026/reviewer_prep_2026-09-05/scripts/r37_flood_n10_update.py --corpus defaults

--corpus (added 2026-09-23, see _common.py::flood_corpus_dirs) -- v08
(default): EXACTLY the mixed-vintage n5(faf1bb12)+ext(83fa97e1) behaviour
documented above, byte-identical output. defaults: there is no vintage
split to mirror -- the no-sampling-params re-run lands all 10 seeds
(42-51) under ONE pair of directories (`JOH_{strict,disabled}_defaults_
gemma3_4b_83fa97e1/Run_{42..51}`, the `strict_n10`/`disabled_n10`
flood_corpus_dirs keys), so this script reads N5_SEEDS and EXT_SEEDS as
two 5-seed SLICES of that single defaults corpus rather than two
directories -- Part 2's "n=10 vs n=5" comparison keeps the same shape
either way. Writes out/r37_flood_n10_update_defaults.{md,csv}. This
script's existing completeness gate already tolerates any subset of the
10 seeds being unlanded (true today: 0/10 for defaults), so Part 1/2
already render "skipped"/PENDING output gracefully.
"""
from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.dirname(__file__)))
import _common as C  # noqa: E402
from _common import PrepError  # noqa: E402
import r23_flood_strict_regen as R23  # noqa: E402  READ-ONLY: _metrics_for, DISPLAY_METRICS.
import r28_trajectory_vs_traditional as R28  # noqa: E402  READ-ONLY: _sign_stats.
import r34_placebo_retry_flood as R34  # noqa: E402  READ-ONLY: _flood_run_completeness,
                                        # _rep_metric, _manifest_fields.

N5_SEEDS = ["42", "43", "44", "45", "46"]
N5_ROOT = {"strict": C.flood_corpus_dirs("v08")["strict"][0],
           "disabled": C.flood_corpus_dirs("v08")["disabled"][0]}
EXT_SEEDS = ["47", "48", "49", "50", "51"]
EXT_ROOT = {"strict": C.flood_corpus_dirs("v08")["strict_ext"][0],
            "disabled": C.flood_corpus_dirs("v08")["disabled_ext"][0]}
N10_SEEDS = N5_SEEDS + EXT_SEEDS
ARMS = ["strict", "disabled"]
METRIC_LABELS = [label for label, _cond in R23.DISPLAY_METRICS]


def _run_dir(arm: str, seed: str, corpus: str = "v08") -> str:
    if corpus != "v08":
        # defaults: one flat 10-seed corpus, no faf1bb12/83fa97e1_ext split.
        root, seeds = C.flood_corpus_dirs(corpus)[f"{arm}_n10"]
        if seed not in seeds:
            raise PrepError(f"_run_dir: seed {seed!r} not in defaults n10 seed list {seeds}")
        return os.path.join(C.FLOOD_RESULTS, root, f"Run_{seed}")
    if seed in N5_SEEDS:
        return os.path.join(C.FLOOD_RESULTS, N5_ROOT[arm], f"Run_{seed}")
    if seed in EXT_SEEDS:
        return os.path.join(C.FLOOD_RESULTS, EXT_ROOT[arm], f"Run_{seed}")
    raise PrepError(f"_run_dir: seed {seed!r} is not in N5_SEEDS or EXT_SEEDS")


