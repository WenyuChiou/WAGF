_cp = R23._csv_precision


def _is_nan(x) -> bool:
    return isinstance(x, float) and x != x


def _degenerate_reason(vals_a: list, vals_b: list) -> str:
    """Round-3-bug fix: `C.paired_t` returns NaN t (hence NaN p_paired_t) when
    the per-seed DIFF has zero variance -- and `_csv_precision` (`R23._cp`)
    round-trips a NaN float through `C.fmt()`'s "NA" display string and then
    tries `float("NA")`, which raises. Rather than special-case the crash
    site, this derives WHY the diff is degenerate directly from the same
    per-seed values the row's own stat was computed from (never hand-typed),
    so the .md can render `n.a. (<reason>)` instead of crashing or showing a
    bare, unexplained "n.a.". Caller must already know the diff is
    zero-variance (checked via `_is_nan` on t/p_paired_t) before calling
    this -- it does not re-check that itself."""
    diffs = [a - b for a, b in zip(vals_a, vals_b)]
    n = len(vals_a)
    sd_a, sd_b = C.sd(vals_a), C.sd(vals_b)
    if sd_a == 0 and sd_b == 0 and vals_a[0] == 0 and vals_b[0] == 0:
        return f"zero variance: both arms 0 on all {n} seeds"
    if sd_a == 0 and sd_b == 0:
        return (f"zero variance: both arms constant ({vals_a[0]:g} and {vals_b[0]:g}) "
                f"on all {n} seeds")
    return f"zero variance: diff constant ({diffs[0]:g}) on all {n} seeds"


def _fmt_stat(x, nd: int, reason: str) -> str:
    """NaN-safe formatter for any paired-stat field (p_paired_t, t, sd_diff,
    p_exact_permutation "if applicable" -- per the task, even though in this
    script's actual usage only t/p_paired_t are ever observed NaN, sd_diff
    and p_exact_permutation are guarded the same way defensively)."""
    if _is_nan(x):
        return f"n.a. ({reason})"
    return f"{_cp(x):.{nd}f}"


def render_md(rows: list, corpus: str = "v08") -> str:
    metrics_rows = [r for r in rows if r["row_type"] == "metrics"]
    skipped_rows = [r for r in rows if r["row_type"] == "skipped"]
    model_pair_rows = [r for r in rows if r["row_type"] == "model_pair_stat"]
    model_pair_pending = [r for r in rows if r["row_type"] == "model_pair_pending"]
    contrast_rows = [r for r in rows if r["row_type"] == "contrast_stat"]
    manifest_rows = [r for r in rows if r["row_type"] == "manifest"]

    n_strict = sum(1 for r in metrics_rows if r["arm"] == "strict")
    n_disabled = sum(1 for r in metrics_rows if r["arm"] == "disabled")

    commit_label = "c3391a53" if corpus == "v08" else "83fa97e1"
    band_label = "faf1bb12" if corpus == "v08" else f"the {corpus} gemma3:4b dirs"
    r24_csv_label = f"r24_flood_contrast_regen{C.corpus_suffix(corpus)}.csv"

    lines = []
    if corpus == "v08":
        lines.append("# R26 -- flood gemma4:12b cross-model arms (c3391a53) vs gemma3:4b "
                      "(faf1bb12), 2026-09-17")
    else:
        lines.append(f"# R26 -- flood gemma4:12b cross-model arms ({corpus} corpus) vs "
                      f"gemma3:4b ({corpus}), 2026-09-23")
        lines.append("")
        lines.append(f"> **Corpus: {corpus}.** {C.flood_sampling_method_text(corpus)}. "
                     f"4b comparator = {band_label}, NOT faf1bb12.")
    lines.append("")
    lines.append(
        f"**Method.** Per-run metrics reuse `r23_flood_strict_regen.py::_metrics_for` "
        f"verbatim (imported); telemetry (mean prompt_tokens/response_tokens/"
        f"llm_latency_ms/tokens_per_second) is read directly from the audit CSV's "
        f"per-call columns (the last-call value per row, not the `_total` cumulative "
        f"variants). Model-paired diff (Part 2) = gemma4:12b - gemma3:4b, literal seed "
        f"42-46. Governed-vs-ungoverned contrast (Part 3) = ungoverned - governed, "
        f"same `C.paired_t`/`C.exact_perm_p` r24 uses; the gemma3:4b contrast row is "
        f"read verbatim from `out/{r24_csv_label}`, never recomputed. "
        f"Every manifest checked has its VALUES verified, not just key presence -- "
        f"`thinking_mode==\"disabled\"`, `llm_timeout_seconds_effective==1800`, "
        f"`model_quantization==\"Q4_K_M\"`, `model` starting with `\"gemma4:12b\"`, "
        f"`git_commit` starting with `\"{commit_label}\"` -- any mismatch raises naming the "
        f"run, field, and offending value; `model_digest` and `git_commit` (short "
        f"form) are reported per run (table below). Strict: {n_strict}/5 seeds "
        f"complete. Disabled: {n_disabled}/5 seeds complete."
    )
    lines.append("")
    lines.append("## Part 1 -- per-seed metrics, gemma4:12b")
    lines.append("")
    metric_labels = [label for label, _ in DISPLAY_METRICS]
    header = ("| arm | seed | " + " | ".join(metric_labels) +
              " | rows | llm_fail | APPROVED | REJECTED | REJ_FALLBACK | fallback% | "
              "wall_h | mean_prompt_tok | mean_resp_tok | mean_latency_ms | mean_tok/s |")
    lines.append(header)
    lines.append("|" + "---|" * (len(metric_labels) + 12))
    for arm in ("strict", "disabled"):
        for r in [rr for rr in metrics_rows if rr["arm"] == arm]:
            mcells = [f"{_cp(r[f'metric__{lbl}']):.3f}" for lbl in metric_labels]
            lines.append(
                f"| {arm} | {r['seed']} | " + " | ".join(mcells) + f" | {r['n_rows']} | "
                f"{r['llm_fail_n']} | {r['status_approved']} | {r['status_rejected']} | "
                f"{r['status_rejected_fallback']} | {_cp(r['fallback_share_pct']):.3f} | "
                f"{_cp(r['wall_hours']):.2f} | {_cp(r['mean_prompt_tokens']):.1f} | "
                f"{_cp(r['mean_response_tokens']):.1f} | "
                f"{_cp(r['mean_llm_latency_ms']):.1f} | "
                f"{_cp(r['mean_tokens_per_second']):.2f} |"
            )
    for r in skipped_rows:
        lines.append(f"| {r['arm']} | {r['seed']} | SKIPPED: {r['reason']} | "
                      + " |" * (len(metric_labels) + 11))
    lines.append("")

    lines.append("## Part 2 -- model-paired comparison, gemma4:12b vs gemma3:4b "
                 "(diff = 12b - 4b)")
    lines.append("")
    for p in model_pair_pending:
        lines.append(f"- **{p['arm']}: PENDING** -- gemma4:12b has {p['n_12b']}/5 "
                     f"complete seeds (gemma3:4b has {p['n_4b']}/5); no comparison "
                     f"computed for this arm.")
    model_pair_pairs = [r for r in rows if r["row_type"] == "model_pair"]
    if model_pair_rows:
        lines.append("")
        lines.append("| arm | metric | mean_diff +/- sd | p_paired_t | p_exact_perm | "
                     "sign-consistent |")
        lines.append("|---|---|---:|---:|---:|:---:|")
        for r in model_pair_rows:
            pairs = [p for p in model_pair_pairs
                     if p["arm"] == r["arm"] and p["metric"] == r["metric"]]
            reason = (_degenerate_reason([p["value_12b"] for p in pairs],
                                          [p["value_4b"] for p in pairs])
                      if _is_nan(r["p_paired_t"]) else None)
            sign_cell = f"n.a. ({reason})" if reason else str(r["all_same_sign"])
            lines.append(
                f"| {r['arm']} | {r['metric']} | {_fmt_stat(r['mean_diff'], 3, reason)} +/- "
                f"{_fmt_stat(r['sd_diff'], 3, reason)} | "
                f"{_fmt_stat(r['p_paired_t'], 4, reason)} | "
                f"{_fmt_stat(r['p_exact_permutation'], 4, reason)} | {sign_cell} |"
            )
    lines.append("")

    lines.append("## Part 3 -- governed-vs-ungoverned contrast, gemma4:12b vs gemma3:4b "
                 "(diff = ungoverned - governed)")
    lines.append("")
    g12b = {r["metric"]: r for r in contrast_rows if r["model"] == "gemma4_12b"}
    g4b = {r["metric"]: r for r in contrast_rows if r["model"] == "gemma3_4b"}
    if not g12b:
        lines.append(f"gemma4:12b contrast: **PENDING** -- disabled arm has "
                     f"{n_disabled}/5 complete seeds. gemma3:4b column shown for "
                     f"reference only.")
        lines.append("")
    lines.append("| metric | gemma4:12b mean_diff +/- sd | gemma4:12b p_paired_t | "
                 "gemma3:4b mean_diff +/- sd | gemma3:4b p_paired_t | same sign "
                 "across models |")
    lines.append("|---|---:|---:|---:|---:|:---:|")
    contrast_pairs = [r for r in rows if r["row_type"] == "contrast_pair"]
    for label in metric_labels:
        if label not in g4b:
            # r24's own --corpus run has no landed data yet (see Part 3's
            # PENDING note above) -- the 4b reference itself is pending, not
            # just the 12b side.
            lines.append(f"| {label} | pending | pending | pending (4b reference pending) "
                         f"| -- | pending |")
            continue
        r4 = g4b[label]
        reason4 = None  # gemma3:4b's own per-seed values are not carried into this
                         # script (its contrast is read verbatim from r24); r24 never
                         # hit this degeneracy for any metric (checked: every gemma3:4b
                         # p_paired_t value read back is finite), so no reason is needed
                         # here in practice -- still guarded via `_fmt_stat` below.
        if label in g12b:
            r12 = g12b[label]
            pairs12 = [p for p in contrast_pairs
                       if p["model"] == "gemma4_12b" and p["metric"] == label]
            reason12 = (_degenerate_reason([p["governed_value"] for p in pairs12],
                                            [p["ungoverned_value"] for p in pairs12])
                        if _is_nan(r12["p_paired_t"]) else None)
            if reason12 or _is_nan(r4["p_paired_t"]):
                same_cell = f"n.a. ({reason12 or 'gemma3:4b side is degenerate'})"
            else:
                same_cell = str((r12["mean_diff"] > 0) == (r4["mean_diff"] > 0))
            lines.append(
                f"| {label} | {_fmt_stat(r12['mean_diff'], 3, reason12)} +/- "
                f"{_fmt_stat(r12['sd_diff'], 3, reason12)} | "
                f"{_fmt_stat(r12['p_paired_t'], 4, reason12)} | "
                f"{_fmt_stat(r4['mean_diff'], 3, reason4)} +/- "
                f"{_fmt_stat(r4['sd_diff'], 3, reason4)} | "
                f"{_fmt_stat(r4['p_paired_t'], 4, reason4)} | {same_cell} |"
            )
        else:
            lines.append(f"| {label} | pending | pending | "
                         f"{_fmt_stat(r4['mean_diff'], 3, reason4)} +/- "
                         f"{_fmt_stat(r4['sd_diff'], 3, reason4)} | "
                         f"{_fmt_stat(r4['p_paired_t'], 4, reason4)} | pending |")
    lines.append("")

    lines.append("## Part 4 -- manifest fields (thinking mode, timeout floor, model)")
    lines.append("")
    lines.append("| arm | seed | model | thinking_mode | timeout_s | model_digest | "
                 "quantization | git_commit |")
    lines.append("|---|---|---|---|---:|---|---|---|")
    for r in manifest_rows:
        lines.append(f"| {r['arm']} | {r['seed']} | {r['model']} | {r['thinking_mode']} | "
                      f"{r['llm_timeout_seconds_effective']} | {r['model_digest']} | "
                      f"{r['model_quantization']} | {r['git_commit_short']} |")
    lines.append("")

    lines.append("## Plain read")
    lines.append("")
    ibr_uncond = next(r for r in model_pair_rows if r["arm"] == "strict"
                       and r["metric"] == "IBR unconditional (%)") if any(
        r["arm"] == "strict" and r["metric"] == "IBR unconditional (%)"
        for r in model_pair_rows) else None
    disabled_status = ("also complete" if n_disabled == 5 else
                        f"still running ({n_disabled}/5 seeds complete)")
    sentences = [
        f"gemma4:12b's strict arm is fully landed ({n_strict}/5 seeds, all "
        f"`integrity_ok`, `thinking_mode=disabled` on every manifest checked); the "
        f"disabled arm is {disabled_status}."
    ]
    if ibr_uncond is not None:
        ibr_pairs = [p for p in model_pair_pairs if p["arm"] == "strict"
                     and p["metric"] == "IBR unconditional (%)"]
        ibr_reason = (_degenerate_reason([p["value_12b"] for p in ibr_pairs],
                                          [p["value_4b"] for p in ibr_pairs])
                      if _is_nan(ibr_uncond["p_paired_t"]) else None)
        sentences.append(
            f"On the model-paired strict-vs-strict comparison, IBR unconditional "
            f"differs by {_fmt_stat(ibr_uncond['mean_diff'], 2, ibr_reason)} pp "
            f"(12b - 4b, p_paired_t={_fmt_stat(ibr_uncond['p_paired_t'], 4, ibr_reason)}, "
            f"sign-consistent={ibr_uncond['all_same_sign'] if not ibr_reason else 'n.a.'} "
            f"across all 5 seeds)."
        )
    if g12b and g4b:
        ibr_c12 = g12b["IBR unconditional (%)"]
        ibr_c4 = g4b["IBR unconditional (%)"]
        same_sign_ibr = (ibr_c12["mean_diff"] > 0) == (ibr_c4["mean_diff"] > 0)
        keeps = "keeps its sign" if same_sign_ibr else "DOES NOT keep its sign"
        if same_sign_ibr and ibr_c4["mean_diff"] > 0:
            direction = " (both positive -- governance lowers IBR on both models)"
        elif same_sign_ibr and ibr_c4["mean_diff"] < 0:
            direction = " (both negative -- governance raises IBR on both models)"
        else:
            direction = ""
        sentences.append(
            f"The governed-vs-ungoverned contrast {keeps} on the larger model: "
            f"unconditional IBR mean_diff (ungoverned - governed) "
            f"{_cp(ibr_c12['mean_diff']):.2f} pp on gemma4:12b vs "
            f"{_cp(ibr_c4['mean_diff']):.2f} pp on gemma3:4b{direction}."
        )
    else:
        sentences.append(
            "The governed-vs-ungoverned contrast on gemma4:12b is pending until the "
            "disabled arm completes; only the gemma3:4b side of that comparison is "
            "available today."
        )
    sentences.append(
        "No number in this report was hand-typed: every cell is rendered from the "
        "same in-memory rows the CSV is written from, and the completeness gates "
        "mean this script can be re-run unchanged once the disabled arm lands."
    )
    lines.append(" ".join(sentences))
    return "\n".join(lines) + "\n"


