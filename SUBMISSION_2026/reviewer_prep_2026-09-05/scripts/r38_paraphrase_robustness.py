SEEDS = ["42", "43"]
ARMS = ["strict", "disabled"]
WORDINGS = ["baseline", "para1", "para2"]
def _root_for(corpus: str) -> dict:
    """{(arm, wording): root_dir_name}, routed entirely through
    `C.flood_corpus_dirs()` -- no literal dir names in this module."""
    cd = C.flood_corpus_dirs(corpus)
    return {
        ("strict", "baseline"): cd["strict"][0],
        ("disabled", "baseline"): cd["disabled"][0],
        ("strict", "para1"): cd["strict_para1"][0],
        ("disabled", "para1"): cd["disabled_para1"][0],
        ("strict", "para2"): cd["strict_para2"][0],
        ("disabled", "para2"): cd["disabled_para2"][0],
    }


ROOT = _root_for("v08")  # kept as a module-level name for readability/back-compat;
                          # its values are sourced from _common.py, never hand-typed.


METRIC_LABELS = [label for label, _cond in R23.DISPLAY_METRICS]
IBR_LABELS = [label for label in METRIC_LABELS if label.startswith("IBR")]
FLOOD_YEARS = set(FIG3.get_flood_years())
ALL_YEARS = set(range(1, 11))
NO_FLOOD_YEARS = sorted(ALL_YEARS - FLOOD_YEARS)


def _run_dir(arm: str, wording: str, seed: str, root: dict) -> str:
    return os.path.join(C.FLOOD_RESULTS, root[(arm, wording)], f"Run_{seed}")


# =============================================================================
# manifest: config-root-path-carries-the-wording-tag check
# =============================================================================
def _find_config_root_field(manifest: dict, tag: str):
    """Returns (field_name, value) for the first string-valued manifest
    field containing `tag`, checking `agent_types_config` FIRST (the field
    this package has already confirmed carries the config-root path on
    both the flood and irrigation domains -- see BACKGROUND), then every
    other string field. None if no field contains it."""
    preferred = manifest.get("agent_types_config")
    if isinstance(preferred, str) and tag in preferred:
        return "agent_types_config", preferred
    for k, v in manifest.items():
        if k == "agent_types_config":
            continue
        if isinstance(v, str) and tag in v:
            return k, v
    return None


# =============================================================================
# Part 1
# =============================================================================
def _part1(rows: list, corpus: str = "v08") -> dict:
    root = _root_for(corpus)
    per_run: dict = {}
    for arm in ARMS:
        for wording in WORDINGS:
            for seed in SEEDS:
                run_dir = _run_dir(arm, wording, seed, root)
                status, reason = R34._flood_run_completeness(run_dir)
                if status == "skipped":
                    print(f"  SKIPPED {arm} {wording} seed {seed}: {reason}")
                    rows.append({"row_type": "skipped", "arm": arm, "wording": wording,
                                 "seed": seed, "reason": reason})
                    continue
                m = R23._metrics_for(run_dir)
                metric_values = {label: m[R34._rep_metric(label)] for label in METRIC_LABELS}
                sim = C.read_csv(os.path.join(run_dir, C.FLOOD_SIM))
                no_flood_rows = [r for r in sim if int(float(r["year"])) in NO_FLOOD_YEARS]
                if not no_flood_rows:
                    raise PrepError(f"{run_dir}: 0 simulation_log rows in no-flood years "
                                     f"{NO_FLOOD_YEARS} -- empty denominator")
                n_do_nothing = sum(1 for r in no_flood_rows
                                   if C.flood_normalize_action(r.get("yearly_decision")) == "do_nothing")
                do_nothing_share_pct = 100.0 * n_do_nothing / len(no_flood_rows)

                row = {"row_type": "run_metrics", "arm": arm, "wording": wording, "seed": seed,
                       "n_rows": m["_n_rows"],
                       "do_nothing_share_no_flood_years_pct": do_nothing_share_pct,
                       "n_no_flood_year_rows": len(no_flood_rows)}
                row.update({f"metric__{i}": metric_values[label]
                            for i, label in enumerate(METRIC_LABELS)})
                rows.append(row)
                rows.append({"row_type": "do_nothing_no_flood", "arm": arm, "wording": wording,
                             "seed": seed, "n_no_flood_year_rows": len(no_flood_rows),
                             "n_do_nothing": n_do_nothing,
                             "do_nothing_share_pct": do_nothing_share_pct})
                print(f"  OK {arm:9s} {wording:8s} seed {seed}: rows={m['_n_rows']} "
                      f"ibr_uncond_final={m['ibr_uncond_final']:.2f}% "
                      f"do_nothing_no_flood={do_nothing_share_pct:.2f}%")

                manifest = R34._manifest_fields(run_dir)
                model = manifest.get("model")
                git_commit = manifest.get("git_commit")
                # v08: only para1/para2 are enforced (baseline was already
                # enforced when r23/r24 first ingested it). defaults: the
                # WHOLE corpus is new, so baseline is enforced too -- but
                # ONLY for model/commit, never for the config-root wording
                # TAG check (baseline carries no "baseline" tag by
                # convention, unlike para1/para2's own tags).
                enforced = (wording != "baseline") if corpus == "v08" else True
                enforce_tag = wording in ("para1", "para2")
                config_field = None
                if enforced:
                    if model != "gemma3:4b":
                        raise PrepError(f"{run_dir}: model={model!r}, expected 'gemma3:4b'")
                    if not str(git_commit or "").startswith("83fa97e1"):
                        raise PrepError(f"{run_dir}: git_commit={git_commit!r}, expected to "
                                         f"start with '83fa97e1'")
                if enforce_tag:
                    found = _find_config_root_field(manifest, wording)
                    if found is None:
                        raise PrepError(f"{run_dir}: no string-valued manifest field contains "
                                         f"{wording!r} -- checked 'agent_types_config' "
                                         f"({manifest.get('agent_types_config')!r}) and every "
                                         f"other string field; cannot confirm the config root "
                                         f"used this wording variant")
                    config_field, config_value = found
                rows.append({"row_type": "manifest_check", "arm": arm, "wording": wording,
                             "seed": seed, "model": model,
                             "git_commit_short": (git_commit or "")[:8],
                             "config_root_field": config_field, "enforced": enforced})

                per_run[(arm, wording, seed)] = metric_values
    return per_run


# =============================================================================
# Part 2 -- governed-vs-ungoverned IBR contrast per wording
# =============================================================================
def _part2(rows: list, per_run: dict) -> None:
    for wording in WORDINGS:
        for label in IBR_LABELS:
            for seed in SEEDS:
                s = per_run.get(("strict", wording, seed))
                d = per_run.get(("disabled", wording, seed))
                if s is None or d is None:
                    missing = [n for n, v in (("strict", s), ("disabled", d)) if v is None]
                    rows.append({"row_type": "skipped", "section": "ibr_contrast",
                                 "wording": wording, "metric": label, "seed": seed,
                                 "reason": f"missing arm(s): {missing}"})
                    continue
                sv, dv = float(s[label]), float(d[label])
                rows.append({"row_type": "ibr_contrast", "wording": wording, "metric": label,
                             "seed": seed, "strict_value": sv, "disabled_value": dv,
                             "diff_strict_minus_disabled": sv - dv})


# =============================================================================
# Part 3 -- wording effect within arm (para - baseline) per seed
# =============================================================================
def _part3(rows: list, per_run: dict) -> None:
    for arm in ARMS:
        for para in ("para1", "para2"):
            for label in METRIC_LABELS:
                for seed in SEEDS:
                    b = per_run.get((arm, "baseline", seed))
                    p = per_run.get((arm, para, seed))
                    if b is None or p is None:
                        missing = [n for n, v in (("baseline", b), (para, p)) if v is None]
                        rows.append({"row_type": "skipped", "section": "wording_effect",
                                     "arm": arm, "wording": para, "metric": label, "seed": seed,
                                     "reason": f"missing wording(s): {missing}"})
                        continue
                    bv, pv = float(b[label]), float(p[label])
                    rows.append({"row_type": "wording_effect", "arm": arm, "wording": para,
                                 "metric": label, "seed": seed, "baseline_value": bv,
                                 "para_value": pv, "diff_para_minus_baseline": pv - bv})


