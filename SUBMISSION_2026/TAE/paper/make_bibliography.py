#!/usr/bin/env python3
"""Generate the References section of manuscript.md from references.bib.

WHY THIS EXISTS (the build-route decision, stated once, here)
-------------------------------------------------------------
There is no bibtex and no biber on PATH, so the `\\bibliography{references}`
route is unavailable. The hand-written-`thebibliography`-inside-the-.tex route
is ALSO unavailable, because manuscript.tex is generated by build.py and
build.py's `_escape_tex` turns every backslash in body text into
`\\textbackslash{}` -- so neither `\\cite{...}` nor `\\begin{thebibliography}`
can survive a trip through manuscript.md.

The route that works, and the one taken:

  references.bib  --(this script)-->  numbered plain-text paragraphs written
                                      into manuscript.md between
                                      <!-- BIBLIOGRAPHY:BEGIN/END --> markers
                                      --(build.py)--> \\section*{References}
                                      followed by ordinary paragraphs.

  In-text citations are literal `[n]` numerals typed in manuscript.md. `[` and
  `]` are not LaTeX specials and pass through `_escape_tex` untouched.

references.bib stays the ONE source. Nothing is transcribed by hand.

USAGE
-----
    python make_bibliography.py            # rewrite manuscript.md's block
    python make_bibliography.py --check    # validate only, write nothing

Run it BEFORE substitute.py, since substitute.py reads manuscript.md.

GUARDS (this script fails loudly rather than emitting a wrong reference list):
  * every key in CITED_ORDER must exist in references.bib;
  * every number 1..N must actually be cited somewhere in the manuscript body
    (an entry nobody cites is a dangling reference);
  * no `[n]` in the body may exceed N (a citation with no entry);
  * the BIBLIOGRAPHY:BEGIN/END markers must both be present, exactly once.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BIB = HERE / "references.bib"
MANUSCRIPT = HERE / "manuscript.md"

BEGIN = "<!-- BIBLIOGRAPHY:BEGIN -- generated by make_bibliography.py from references.bib; do not hand-edit -->"
END = "<!-- BIBLIOGRAPHY:END -->"

# Order of first appearance in the manuscript body. The index in this list,
# plus one, IS the citation number. Adding an entry here without adding the
# matching [n] to the body will fail the dangling-reference guard.
CITED_ORDER = [
    "wang2026agentspec",      # [1]  section 1, para 1 and para 3
    "rebedea2023nemo",        # [2]  section 1, para 1
    "kang2026policyguard",    # [3]  section 1, para 1
    "yuan2026saver",          # [4]  section 1, para 1 and para 3
    "grossi2007ubilex",       # [5]  section 1, para 1 (norm enforcement in e-institutions)
    "esteva2004ameli",        # [6]  section 1, para 1
    "dignum2004opera",        # [7]  section 1, para 1
    "hubner2002moise",        # [8]  section 1, para 1
    "gao2026looping",         # [9]  section 1, para 4
    "rosenbaum1984adjustment",  # [10] section 1, para 4 (same sentence, after [9])
    "rogers1975pmt",          # [11] section 2
    # [12]-[14] added 2026-08-03: the evaluation-validity positioning paragraph in
    # section 1. Each was verified TWICE on 2026-08-03 -- once by a proposing pass
    # and once by an independent pass that searched arXiv by TITLE rather than
    # trusting the handed identifier, so a fabricated title would have returned
    # nothing. The query run, the verbatim abstract clause the body sentence
    # paraphrases, and the drift prohibitions are in each entry's note field.
    "bean2025construct",      # [12] section 1, para 3 (construct validity, NeurIPS 2025 D&B)
    "kapoor2024agents",       # [13] section 1, para 3 (agent-evaluation axis; PREPRINT)
    "liu2026charge",          # [14] section 1, para 3 (nearest method precedent; PREPRINT)
]

# BibTeX accent macros -> the Unicode character. build.py's _TEX_UNICODE maps
# each of these back to a LaTeX accent for the pdflatex branch and python-docx
# writes them directly, so both outputs render the same glyph.
_ACCENTS = {
    r"{\'i}": "í",   # i acute
    r"{\'e}": "é",
    r"{\'a}": "á",
    r"{\'o}": "ó",
    r"{\'u}": "ú",
    r"{\"u}": "ü",   # u umlaut
    r"{\"o}": "ö",
    r"{\"a}": "ä",
    r"{\~a}": "ã",   # a tilde
    r"{\~n}": "ñ",
    r"{\c c}": "ç",
}


def de_tex(s: str) -> str:
    for macro, char in _ACCENTS.items():
        s = s.replace(macro, char)
    if "\\" in s or "{" in s or "}" in s:
        raise ValueError(
            f"unhandled TeX markup left in bib field after accent expansion: {s!r}. "
            f"Add the macro to _ACCENTS in make_bibliography.py."
        )
    return s


# ---------------------------------------------------------------------------
# A small brace-balanced .bib parser. Not general BibTeX -- it only needs to
# round-trip the constrained shape references.bib is written in, and it raises
# rather than guessing.
# ---------------------------------------------------------------------------

_ENTRY_RE = re.compile(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", re.MULTILINE)


def parse_bib(path: Path) -> dict[str, dict[str, str]]:
    text = path.read_text(encoding="utf-8")
    entries: dict[str, dict[str, str]] = {}
    for m in _ENTRY_RE.finditer(text):
        etype, key = m.group(1).lower(), m.group(2)
        # Walk forward to the matching close brace of the entry.
        depth = 1
        i = m.end() - 1  # sits on the ',' after the key; step from the '{'
        i = text.index("{", m.start())
        depth = 0
        for j in range(i, len(text)):
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
                if depth == 0:
                    body = text[m.end():j]
                    break
        else:
            raise ValueError(f"unbalanced braces in entry {key!r}")

        fields: dict[str, str] = {"__type__": etype}
        for fm in re.finditer(r"(\w+)\s*=\s*\{", body):
            name = fm.group(1).lower()
            d = 1
            k = fm.end()
            while k < len(body) and d:
                if body[k] == "{":
                    d += 1
                elif body[k] == "}":
                    d -= 1
                k += 1
            raw = body[fm.end():k - 1]
            fields[name] = " ".join(raw.split())
        entries[key] = fields
    if not entries:
        raise ValueError(f"no entries parsed from {path}")
    return entries


def format_authors(raw: str) -> str:
    names = [de_tex(n.strip()) for n in raw.split(" and ")]
    if len(names) == 1:
        return names[0]
    if len(names) == 2:
        return f"{names[0]} and {names[1]}"
    return ", ".join(names[:-1]) + ", and " + names[-1]


def format_entry(key: str, e: dict[str, str]) -> str:
    t = e["__type__"]
    parts = [format_authors(e["author"]) + "."]
    parts.append(de_tex(e["title"]).rstrip(".") + ".")

    if t in ("inproceedings", "incollection"):
        venue = "In " + de_tex(e["booktitle"])
        if "series" in e:
            venue += ", " + de_tex(e["series"])
        if "pages" in e:
            venue += ", pages " + de_tex(e["pages"]).replace("--", "–")
        venue += ", " + e["year"]
        if "publisher" in e:
            venue += ". " + de_tex(e["publisher"])
        parts.append(venue + ".")
    elif t == "article":
        loc = de_tex(e["journal"])
        if "volume" in e:
            loc += ", " + e["volume"]
            if "number" in e:
                loc += "(" + e["number"] + ")"
        if "pages" in e:
            loc += ":" + de_tex(e["pages"]).replace("--", "–")
        loc += ", " + e["year"]
        parts.append(loc + ".")
    elif t == "phdthesis":
        loc = "PhD thesis, " + de_tex(e["school"]) + ", " + e["year"]
        if "series" in e:
            loc += ". " + de_tex(e["series"])
        parts.append(loc + ".")
    elif t == "misc":
        parts.append("Preprint, " + e["year"] + ".")
    else:
        raise ValueError(f"entry {key!r}: unhandled type {t!r}")

    # Optional. Some works are known in the literature by a model name the title
    # never mentions -- OperA [7] and MOISE+ [8] are both cited that way in
    # section 1, and a reader following either number would otherwise land on a
    # title with no way to confirm it is the right work. The name goes here
    # rather than into the title, which is quoted as published.
    if "identifies" in e:
        parts.append("Introduces the " + de_tex(e["identifies"]) + " model.")

    if "doi" in e:
        parts.append("doi:" + e["doi"] + ".")
    if "eprint" in e:
        parts.append("arXiv:" + e["eprint"] + ".")
    elif "url" in e and "doi" not in e:
        parts.append(e["url"])

    return " ".join(parts)


def render(entries: dict[str, dict[str, str]]) -> list[str]:
    out = []
    for n, key in enumerate(CITED_ORDER, start=1):
        if key not in entries:
            raise ValueError(f"CITED_ORDER key {key!r} is not in {BIB.name}")
        out.append(f"[{n}] {format_entry(key, entries[key])}")
    return out


_BODY_CITE_RE = re.compile(r"\[(\d+)\]")


def main() -> int:
    entries = parse_bib(BIB)
    refs = render(entries)
    n_refs = len(refs)

    text = MANUSCRIPT.read_text(encoding="utf-8")
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        print(
            f"FAIL: manuscript.md must contain the BIBLIOGRAPHY:BEGIN and "
            f"BIBLIOGRAPHY:END markers exactly once each "
            f"(found {text.count(BEGIN)} and {text.count(END)}).",
            file=sys.stderr,
        )
        return 1

    head, rest = text.split(BEGIN, 1)
    _old, tail = rest.split(END, 1)

    # Citation guards run against the body only -- everything before the
    # generated block. Numbers inside the reference list itself are labels,
    # not citations, and must not count as uses.
    body_cites = {int(x) for x in _BODY_CITE_RE.findall(head)}
    dangling = [n for n in range(1, n_refs + 1) if n not in body_cites]
    overrun = sorted(n for n in body_cites if n > n_refs)

    if dangling:
        print(
            "FAIL: reference(s) in the list that nothing in the body cites: "
            + ", ".join(f"[{n}] ({CITED_ORDER[n - 1]})" for n in dangling),
            file=sys.stderr,
        )
        return 1
    if overrun:
        print(
            "FAIL: body cites number(s) with no reference entry: "
            + ", ".join(f"[{n}]" for n in overrun),
            file=sys.stderr,
        )
        return 1

    block = "\n" + "\n\n".join(refs) + "\n\n"
    new_text = head + BEGIN + block + END + tail

    if "--check" in sys.argv[1:]:
        status = "up to date" if new_text == text else "STALE -- rerun without --check"
        print(f"{n_refs} references, {len(body_cites)} cited in body. manuscript.md is {status}.")
        return 0 if new_text == text else 1

    MANUSCRIPT.write_text(new_text, encoding="utf-8")
    print(f"OK: wrote {n_refs} references into {MANUSCRIPT.name}; all cited in body.")
    for line in refs:
        print("  " + line[:110] + ("..." if len(line) > 110 else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
